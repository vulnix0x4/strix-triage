"""Generate a candidate Strix/YARA-style detection rule from a sample.

Given an analysis report, pick the most *distinctive* evidence — unusual static
strings, emulation-recovered strings, notable imports — and emit a ready-to-tune
``.strx`` rule. This is defensive signature authoring: turn one confirmed-bad
sample into a detection others can reuse. The output is a starting point an
analyst should review, not a finished production rule.
"""

from __future__ import annotations

import re
from typing import Optional

from ..core.model import AnalysisReport

# words too generic to make a good signature
_COMMON = {
    "microsoft", "windows", "program", "software", "system32", "kernel32",
    "function", "library", "assembly", "version", "copyright", "description",
    "advapi32", "user32", "msvcrt", "the", "error", "warning", "loading",
}
_GOODCHARS = re.compile(r"[A-Za-z0-9 ._\\/:%@!?\-]{6,}")


def _score_string(s: str) -> float:
    """Higher = more distinctive / rule-worthy."""
    s2 = s.strip()
    if len(s2) < 6 or len(s2) > 120:
        return 0.0
    low = s2.lower()
    if low in _COMMON or any(w == low for w in _COMMON):
        return 0.0
    score = min(len(s2), 40) / 10.0
    if any(c in s2 for c in "\\/:%@"):
        score += 2          # paths, URLs, format strings
    if re.search(r"https?://|\.onion|\.php|cmd|powershell|vssadmin", low):
        score += 4
    if re.search(r"[A-Z]", s2) and re.search(r"[a-z]", s2) and re.search(r"\d", s2):
        score += 1          # mixed-case-digit → likely a unique token
    # penalise strings that are mostly one repeated char
    if len(set(s2)) < max(3, len(s2) // 6):
        score -= 2
    return max(0.0, score)


def _escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def generate(report: AnalysisReport, max_strings: int = 8,
             rule_name: Optional[str] = None) -> str:
    f = report.file
    sha = f.hashes.get("sha256", "")
    name = rule_name or f"Strix_auto_{sha[:12] or 'sample'}"

    # gather candidate strings: static sample + emulation-decoded (high value)
    candidates: list[tuple[float, str, str]] = []  # (score, value, note)
    for s in report.sections.get("strings_sample", []):
        v = s.get("value", "")
        sc = _score_string(v)
        if sc > 0:
            candidates.append((sc, v, s.get("encoding", "ascii")))
    for r in report.sections.get("decoded_strings", []):
        v = r.get("value", "")
        sc = _score_string(v)
        if sc > 0:
            candidates.append((sc + 3, v, r.get("encoding", "ascii")))  # decoded = extra weight

    # de-dup by value, keep best score
    best: dict[str, tuple[float, str]] = {}
    for sc, v, enc in candidates:
        if v not in best or sc > best[v][0]:
            best[v] = (sc, enc)
    ranked = sorted(best.items(), key=lambda kv: kv[1][0], reverse=True)[:max_strings]

    attack = report.attack_techniques[:10]
    lines = [f"rule {name} {{", "    meta:",
             f'        description = "Auto-generated from a {report.verdict.value} sample (Strix)"',
             f'        sha256      = "{sha}"',
             f'        imphash     = "{f.hashes.get("imphash", "")}"',
             f'        score       = "{report.score}"']
    if attack:
        lines.append(f'        attack      = {", ".join(attack)}')
    lines.append("    strings:")

    str_names = []
    if ranked:
        for i, (val, (_sc, enc)) in enumerate(ranked):
            nm = f"$s{i}"
            str_names.append(nm)
            mods = " wide" if enc == "utf-16le" else ""
            lines.append(f'        {nm} = "{_escape(val)}"{mods} ascii nocase')
    else:
        lines.append('        $mz = { 4D 5A }   // no distinctive strings found; tune manually')
        str_names.append("$mz")

    # condition: require a healthy fraction of the distinctive strings
    if len(str_names) >= 4:
        need = max(2, len(str_names) // 2)
        cond = f"{need} of them"
    else:
        cond = "all of them"
    imp = f.hashes.get("imphash", "")
    lines.append("    condition:")
    lines.append(f"        {cond}")
    lines.append("}")
    header = (f"// Auto-generated by Strix. Review before deploying.\n"
              f"// Sample: {f.path}\n"
              f"// imphash pivot: {imp}\n")
    return header + "\n".join(lines) + "\n"
